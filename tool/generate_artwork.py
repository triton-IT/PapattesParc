"""Generate runtime art without changing source PNGs. Requires Pillow 11.3.0.

Run: py -3.13 tool/generate_artwork.py
Verify: py -3.13 tool/generate_artwork.py --check
"""
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import sys
import re
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/optimized'
GROUPS = ('level_art', 'animal_markers', 'match3', 'mahjong', 'solitaire', 'sokoban', 'food_sort')
SOURCES = sorted({p for group in GROUPS for p in (ROOT / 'assets' / group).rglob('*.png')} |
                 {ROOT / 'assets/park_map.png'})

def build(source):
    logical = source.relative_to(ROOT).as_posix()
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    image = Image.open(source)
    background = ('level_art/' in logical or logical.endswith('cover.png') or
                  '/background-' in logical)
    widths = sorted({min(w, image.width) for w in (320, 640, 1280, image.width)}) if background else [image.width]
    variants = []
    for width in widths:
        target = OUT / source.relative_to(ROOT / 'assets').with_suffix('')
        target = target.parent / (target.name + f'-{width}.webp')
        target.parent.mkdir(parents=True, exist_ok=True)
        resized = image.copy()
        if width < image.width:
            resized = image.resize((width, max(1, round(image.height * width / image.width))), Image.Resampling.LANCZOS)
        resized.save(target, 'WEBP', quality=90, lossless=not background, method=6, exact=True)
        variants.append({'width': resized.width, 'height': resized.height,
                         'path': target.relative_to(ROOT).as_posix(), 'bytes': target.stat().st_size,
                         'sha256': hashlib.sha256(target.read_bytes()).hexdigest()})
    return logical, {'sha256': digest, 'sourceBytes': source.stat().st_size, 'variants': variants}

def main():
    manifest_path = OUT / 'manifest.json'
    if '--check' in sys.argv:
        manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
        assert set(manifest) == {p.relative_to(ROOT).as_posix() for p in SOURCES}, 'source inventory changed'
        for path, entry in manifest.items():
            assert hashlib.sha256((ROOT / path).read_bytes()).hexdigest() == entry['sha256'], path
            for variant in entry['variants']:
                assert (ROOT / variant['path']).stat().st_size == variant['bytes'], variant['path']
                assert hashlib.sha256((ROOT / variant['path']).read_bytes()).hexdigest() == variant['sha256'], variant['path']
        dart = (ROOT / 'lib/shared/artwork_manifest.dart').read_text(encoding='utf8')
        declarations = re.findall(r'"([^"]+\.png)":\s*\[(.*?)\]', dart, re.S)
        assert {logical for logical, _ in declarations} == set(manifest), 'Dart inventory changed'
        for logical, records in declarations:
            parsed = re.findall(r'path:\s*"([^"]+)",\s*width:\s*(\d+),\s*height:\s*(\d+)', records)
            assert parsed == [(v['path'], str(v['width']), str(v['height'])) for v in manifest[logical]['variants']], logical
        print(f'Artwork manifest verified: {len(manifest)} sources')
        return
    OUT.mkdir(parents=True, exist_ok=True)
    canonical = {}
    aliases = {}
    for source in SOURCES:
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        original = canonical.setdefault(digest, source)
        aliases[source.relative_to(ROOT).as_posix()] = original.relative_to(ROOT).as_posix()
    with ThreadPoolExecutor(max_workers=4) as pool:
        generated = dict(pool.map(build, canonical.values()))
    manifest = {logical: generated[original] for logical, original in aliases.items()}
    referenced = {variant['path'] for entry in manifest.values() for variant in entry['variants']}
    for stale in OUT.rglob('*.webp'):
        assert stale.resolve().is_relative_to(OUT.resolve())
        if stale.relative_to(ROOT).as_posix() not in referenced:
            stale.unlink()
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    dart = '// Generated by tool/generate_artwork.py. Do not edit.\n'
    dart += 'const artworkVariants = <String, List<({String path, int width, int height})>>{\n'
    for logical, entry in manifest.items():
        dart += f'  {json.dumps(logical)}: [\n'
        for v in entry['variants']:
            dart += f'    (path: {json.dumps(v["path"])}, width: {v["width"]}, height: {v["height"]}),\n'
        dart += '  ],\n'
    dart += '};\n'
    (ROOT / 'lib/shared/artwork_manifest.dart').write_text(dart, encoding='utf-8')
    print(f'{len(manifest)} sources; {sum((ROOT / path).stat().st_size for path in referenced):,} runtime bytes')

if __name__ == '__main__':
    main()
