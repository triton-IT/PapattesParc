List<SolitaireLevelDefinition> buildSolitaireCampaign(List<ParkStage> stages) =>
    [
      for (var index = 0; index < stages.length; index++)
        SolitaireLevelDefinition(
          stage: stages[index],
          mode: _mode(index + 1),
          seed: _seeds[index],
          targetRedeals: _targetRedeals[index],
        ),
    ];

SolitaireMode _mode(int level) {
  if (level <= 15) return SolitaireMode.drawOne;
  if (level <= 30) return SolitaireMode.drawThree;
  return level.isOdd ? SolitaireMode.drawOne : SolitaireMode.drawThree;
}

